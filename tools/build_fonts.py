#!/usr/bin/env python3
"""Wrap TTF files as JS so the app works from file:// (no fetch needed).

Usage: python3 tools/build_fonts.py <dir with <id>.ttf files>
Reads tools/fonts.txt (id|name|group|google-fonts path) and writes
fonts/<id>.js plus fonts/manifest.js.
"""
import base64, json, os, sys

src = sys.argv[1]
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = []
for line in open(os.path.join(root, 'tools', 'fonts.txt')):
    line = line.strip()
    if not line:
        continue
    fid, name, group, _ = line.split('|')
    ttf = os.path.join(src, fid + '.ttf')
    if not os.path.exists(ttf):
        print('missing', fid)
        continue
    b64 = base64.b64encode(open(ttf, 'rb').read()).decode()
    with open(os.path.join(root, 'fonts', fid + '.js'), 'w') as f:
        f.write('(window.FONT_DATA = window.FONT_DATA || {})[%s] = "%s";\n' % (json.dumps(fid), b64))
    out.append([fid, name, group])
with open(os.path.join(root, 'fonts', 'manifest.js'), 'w') as f:
    f.write('// generated by tools/build_fonts.py: [id, name, group]\nwindow.FONT_LIST = %s;\n' % json.dumps(out, indent=0))
print(len(out), 'fonts')
